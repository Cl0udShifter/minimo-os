-- Configuración de Hyprland de Minimo OS (API Lua, Hyprland 0.55+).
-- Cada parte vive en hypr/minimo/*.lua; minimo.lua agrega los atajos de la shell.

hl.config({ autogenerated = false })

-- Al iniciar: exportar el entorno a systemd y levantar la sesión (minimo-shell.service).
hl.on("hyprland.start", function()
	hl.exec_cmd("dbus-update-activation-environment --systemd --all")
	hl.exec_cmd("systemctl --user start hyprland-session.target")
end)

require("minimo.apariencia")   -- huecos, bordes, esquinas, sombras, animaciones, colores
require("minimo.entrada")      -- teclado, mouse, touchpad, gestos
require("minimo.monitores")    -- monitores (propio de cada PC; lo escribe Ajustes › Pantalla)
require("minimo.reglas")       -- reglas de ventanas y capas
require("minimo.atajos")       -- atajos de teclado
require("minimo")              -- atajos de la shell (Super+B, etc.)
